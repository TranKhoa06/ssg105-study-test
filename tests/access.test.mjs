import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile } from 'node:fs/promises';
const require=createRequire(process.env.SSG_TEST_DEPENDENCIES||import.meta.url);
const {PGlite}=require('@electric-sql/pglite');

test('database denies anonymous/pending/blocked access and isolates progress between members',async()=>{
  const db=new PGlite();
  await db.exec(`create role anon;create role authenticated;create schema auth;create schema storage;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    grant usage on schema auth,storage to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
    alter table storage.objects enable row level security;grant select on storage.objects to authenticated;
  `);
  await db.exec(await readFile(new URL('../backend/schema.sql',import.meta.url),'utf8'));
  const alice='11111111-1111-4111-8111-111111111111',bob='22222222-2222-4222-8222-222222222222',pending='33333333-3333-4333-8333-333333333333';
  await db.exec(`insert into auth.users values('${alice}'),('${bob}'),('${pending}');
    update public.ssg_members set status='active' where user_id in ('${alice}','${bob}');
    insert into public.ssg_questions values(1,'{"id":1,"prompt":"Private fixture"}',true),(2,'{"id":2}',false);
    insert into storage.objects(bucket_id,name) values('ssg105-private','assets/questions/1.jpg');`);
  async function as(id,role='authenticated'){await db.exec(`reset role;select set_config('request.jwt.claim.sub','${id}',false);set role ${role};`);}
  await as('','anon');
  await assert.rejects(db.query('select * from public.ssg_questions'),/permission denied/);
  await as(pending);
  assert.equal((await db.query('select * from public.ssg_questions')).rows.length,0);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  const payload={subject:'SSG105',version:1,attempts:[],bookmarks:[1],session:null};
  await assert.rejects(db.query('select public.ssg_save_progress($1::jsonb,0)',[JSON.stringify(payload)]),/Access denied/);
  await as(alice);
  assert.equal((await db.query('select * from public.ssg_questions')).rows.length,1);
  assert.equal((await db.query('select * from storage.objects')).rows.length,1);
  assert.equal((await db.query('select * from public.ssg_members')).rows.length,1);
  await assert.rejects(db.exec("update public.ssg_members set role='admin'"),/permission denied/);
  const first=await db.query('select public.ssg_save_progress($1::jsonb,0) as revision',[JSON.stringify(payload)]);
  assert.equal(Number(first.rows[0].revision),1);
  await assert.rejects(db.query('select public.ssg_save_progress($1::jsonb,0)',[JSON.stringify(payload)]),/another device/);
  await assert.rejects(db.query('select public.ssg_save_progress($1::jsonb,1)',['{}']),/Invalid progress/);
  await as(bob);
  assert.equal((await db.query('select * from public.ssg_progress')).rows.length,0);
  await db.query('select public.ssg_save_progress($1::jsonb,0)',[JSON.stringify({...payload,bookmarks:[]})]);
  await assert.rejects(db.exec(`update public.ssg_progress set data='{}' where user_id='${alice}'`),/permission denied/);
  await as(alice);
  const own=await db.query('select data from public.ssg_progress');
  assert.equal(own.rows.length,1);assert.deepEqual(own.rows[0].data.bookmarks,[1]);
  await db.exec(`reset role;update public.ssg_members set status='blocked' where user_id='${alice}';`);
  await as(alice);
  assert.equal((await db.query('select * from public.ssg_questions')).rows.length,0);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  assert.equal((await db.query('select * from public.ssg_progress')).rows.length,0);
  await assert.rejects(db.query('select public.ssg_save_progress($1::jsonb,1)',[JSON.stringify(payload)]),/Access denied/);
  await db.close();
});
